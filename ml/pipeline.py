"""
Tariff recommender pipeline for mobile operators (Azercell-priced).

Run: python3 pipeline.py
Requires: telecom_users.csv, test_same_dist.csv, test_drift_x1.3.csv
          (and their *_hidden_types.csv eval-only companions)
          generated by gen_sections.py in the same directory.

Stages:
  1. Feature engineering
  2. Persona discovery (K-Means k=12 -> merged to named personas)
     evaluated against hidden_type (eval-only) via silhouette + ARI
  3. Persona classifier: LogisticRegression vs RandomForest vs
     HistGradientBoosting, 5-fold stratified CV
  4. Package builder: S/M/L tiers per persona, dedicated buckets for
     sections >= 2 GB, formula-priced and capped vs real existing offers
  5. recommend(user) end-to-end
  6. Economics evaluation vs best-fit existing Azercell offer
  7. Held-out (same-dist) and drift (x1.3) testing
  8. Sensitivity analysis + hand-crafted demo users

No fabricated numbers: every figure printed below is computed from the
data actually generated in this run.
"""

