# ---------------------------------------------------------------------------
# Real Azercell price research (see docs/tariff-price-research.md).
# VERIFIED = scraped from azercell.com/app. ASSUMED = inferred, disclosed.
# ---------------------------------------------------------------------------
EXISTING_OFFERS = [
    # (gb, price_azn, source)
    (3, 9, "verified_28day"),
    (6, 12, "verified_28day"),
    (12, 19, "verified_28day"),
    (30, 29, "verified_28day"),
    (56, 39, "verified_28day"),
    (60, 60, "verified_premium_plus"),
    (100, 90, "verified_premium_plus"),
    (5, 12, "assumed_digimax"),
    (10, 18, "assumed_digimax"),
    (25, 30, "assumed_digimax"),
]


def cheapest_existing_offer(gb: float) -> tuple[float, str]:
    """Cheapest real/assumed offer with capacity >= gb. Falls back to the
    fitted formula (5.27*sqrt(gb)) if gb exceeds every listed offer."""
    candidates = [(price, src) for cap, price, src in EXISTING_OFFERS if cap >= gb]
    if candidates:
        price, src = min(candidates, key=lambda x: x[0])
        return price, src
    return round(5.27 * np.sqrt(gb), 2), "fitted_formula_extrapolated"


# ---------------------------------------------------------------------------
# 1. Feature engineering
# ---------------------------------------------------------------------------
def engineer_features(df: pd.DataFrame) -> pd.DataFrame:
    f = pd.DataFrame(index=df.index)
    total = df[SECTIONS].sum(axis=1).clip(lower=1e-6)
    f["total_gb"] = total
    for s in SECTIONS:
        f[f"log_{s}"] = np.log1p(df[s])
        f[f"share_{s}"] = df[s] / total
    yt_nf = df["youtube_gb"] + df["netflix_gb"]
    f["yt_vs_netflix"] = df["youtube_gb"] / yt_nf.clip(lower=1e-6)
    tt_ig = df["tiktok_gb"] + df["instagram_gb"]
    f["tiktok_vs_instagram"] = df["tiktok_gb"] / tt_ig.clip(lower=1e-6)
    return f


# ---------------------------------------------------------------------------
# 2. Persona discovery via K-Means(k=12) merged to named personas
# ---------------------------------------------------------------------------
NAMED_PERSONAS = [
    "Light user",
    "Heavy Video streamer (YouTube)",
    "Video streamer (Netflix)",
    "Everyday all-rounder",
    "Remote worker (Teams/Zoom)",
    "Social scroller (TikTok)",
    "Gamer",
    "Messaging-first (WhatsApp)",
    "Social scroller (Instagram)",
    "AI power user",
]


def name_cluster(center_shares: pd.Series, total_gb: float) -> str:
    """Rule-based naming of a cluster centroid onto one of the 10 named
    personas, using its dominant section share and total usage."""
    dominant = center_shares.idxmax()
    dom_share = center_shares[dominant]

    if total_gb < 4.5 and dom_share < 0.45:
        return "Light user"
    if dominant == "gaming_gb" and dom_share > 0.35:
        return "Gamer"
    if dominant == "ai_apps_gb" and dom_share > 0.25:
        return "AI power user"
    if dominant == "collaboration_gb" and dom_share > 0.25:
        return "Remote worker (Teams/Zoom)"
    if dominant == "communication_gb" and dom_share > 0.3:
        return "Messaging-first (WhatsApp)"
    if dominant == "video_streaming_gb" and dom_share > 0.32:
        # split by which sub-app dominates within this centroid is handled
        # at assignment time using the raw youtube/netflix ratio; default:
        return "Heavy Video streamer (YouTube)"
    if dominant == "social_media_gb" and dom_share > 0.32:
        return "Social scroller (TikTok)"
    return "Everyday all-rounder"


def discover_personas(df: pd.DataFrame, feats: pd.DataFrame, k: int = 12, seed: int = RNG_SEED):
    share_cols = [f"share_{s}" for s in SECTIONS]
    ratio_cols = ["yt_vs_netflix", "tiktok_vs_instagram"]
    X = feats[[f"log_{s}" for s in SECTIONS] + share_cols + ratio_cols]
    scaler = StandardScaler()
    Xs = scaler.fit_transform(X)

    km = KMeans(n_clusters=k, random_state=seed, n_init=10)
    raw_labels = km.fit_predict(Xs)

    sil = silhouette_score(Xs, raw_labels)

    # stability across restarts
    km2 = KMeans(n_clusters=k, random_state=seed + 1, n_init=10)
    raw_labels2 = km2.fit_predict(Xs)
    stability_ari = adjusted_rand_score(raw_labels, raw_labels2)

    # Name each of the k raw clusters onto one of the 10 named personas,
    # splitting video/social clusters by their YT-vs-Netflix / TikTok-vs-IG
    # ratio so both members of each pair can appear.
    cluster_names = {}
    for c in range(k):
        mask = raw_labels == c
        if mask.sum() == 0:
            continue
        center_shares = feats.loc[mask, share_cols].mean()
        center_shares.index = SECTIONS
        total_gb = feats.loc[mask, "total_gb"].mean()
        name = name_cluster(center_shares, total_gb)

        if name == "Heavy Video streamer (YouTube)":
            ytr = df.loc[mask, "youtube_gb"].sum() / (df.loc[mask, "youtube_gb"].sum() + df.loc[mask, "netflix_gb"].sum() + 1e-6)
            name = "Heavy Video streamer (YouTube)" if ytr >= 0.5 else "Video streamer (Netflix)"
        if name == "Social scroller (TikTok)":
            ttr = df.loc[mask, "tiktok_gb"].sum() / (df.loc[mask, "tiktok_gb"].sum() + df.loc[mask, "instagram_gb"].sum() + 1e-6)
            name = "Social scroller (TikTok)" if ttr >= 0.5 else "Social scroller (Instagram)"

        cluster_names[c] = name

    persona = pd.Series([cluster_names[c] for c in raw_labels], index=df.index, name="persona")
    diag = {"silhouette": sil, "stability_ari": stability_ari, "scaler": scaler, "n_clusters_used": len(cluster_names)}
    return persona, diag


# ---------------------------------------------------------------------------
# 3. Classifier: LR vs RF vs HGB, 5-fold stratified CV
# ---------------------------------------------------------------------------
def train_classifier(feats: pd.DataFrame, y: pd.Series, seed: int = RNG_SEED):
    X_raw = feats.drop(columns=["total_gb"]).values
    clf_scaler = StandardScaler().fit(X_raw)
    X = clf_scaler.transform(X_raw)
    labels = sorted(y.unique())
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed)

    models = {
        "LogisticRegression": LogisticRegression(max_iter=2000),
        "RandomForest": RandomForestClassifier(n_estimators=300, random_state=seed, n_jobs=-1),
        "ExtraTrees": ExtraTreesClassifier(n_estimators=400, random_state=seed, n_jobs=-1),
        "HistGradientBoosting": HistGradientBoostingClassifier(random_state=seed),
        "GradientBoosting": GradientBoostingClassifier(random_state=seed),
        "SVM_RBF": SVC(kernel="rbf", C=4.0, gamma="scale"),
        "MLP": MLPClassifier(hidden_layer_sizes=(64, 32), max_iter=800, random_state=seed, early_stopping=True),
    }

    results = {}
    oof_preds = {}
    for name, model in models.items():
        preds = cross_val_predict(model, X, y, cv=cv, n_jobs=1)
        acc = accuracy_score(y, preds)
        macro_f1 = f1_score(y, preds, average="macro")
        fold_accs = []
        for _, test_idx in cv.split(X, y):
            fold_accs.append(accuracy_score(y.values[test_idx], preds[test_idx]))
        results[name] = {
            "accuracy": acc,
            "macro_f1": macro_f1,
            "fold_acc_min": min(fold_accs),
            "fold_acc_max": max(fold_accs),
        }
        oof_preds[name] = preds

    best_name = max(results, key=lambda n: results[n]["macro_f1"])
    best_model = models[best_name].fit(X, y)
    cm = confusion_matrix(y, oof_preds[best_name], labels=labels)
    report = classification_report(y, oof_preds[best_name], labels=labels, zero_division=0)

    return {
        "results": results,
        "best_name": best_name,
        "best_model": best_model,
        "scaler": clf_scaler,
        "labels": labels,
        "confusion_matrix": cm,
        "classification_report": report,
        "feature_columns": list(feats.drop(columns=["total_gb"]).columns),
    }


# ---------------------------------------------------------------------------
# 4. Package builder: S/M/L tiers per persona
# ---------------------------------------------------------------------------
def build_packages(df: pd.DataFrame, persona: pd.Series):
    total = df[SECTIONS].sum(axis=1)
    work = df.copy()
    work["persona"] = persona.values
    work["total_gb"] = total.values

    packages = {}
    for pname, group in work.groupby("persona"):
        if len(group) < 10:
            continue
        q1, q2 = group["total_gb"].quantile([1 / 3, 2 / 3])
        tiers = {
            "S": group[group["total_gb"] <= q1],
            "M": group[(group["total_gb"] > q1) & (group["total_gb"] <= q2)],
            "L": group[group["total_gb"] > q2],
        }

        prev_price = 0.0
        for tname in ["S", "M", "L"]:
            tgroup = tiers[tname]
            if len(tgroup) == 0:
                continue

            p85 = tgroup["total_gb"].quantile(0.85)
            pack_total_gb = round(p85 * 1.10, 2)
            coverage = (tgroup["total_gb"] <= pack_total_gb).mean()

            buckets = {}
            allocated = 0.0
            for s in SECTIONS:
                s85 = tgroup[s].quantile(0.85) * 1.10
                if s85 >= 2.0:
                    buckets[s] = round(s85, 2)
                    allocated += s85
            general_pool = max(0.0, round(pack_total_gb - allocated, 2))

            n_buckets = len(buckets)
            bucket_premium = min(0.12, 0.06 * n_buckets)
            formula_price = 5.27 * np.sqrt(max(pack_total_gb, 0.1)) * (1 + bucket_premium)

            existing_price, existing_src = cheapest_existing_offer(pack_total_gb)
            cap_price = 0.92 * existing_price
            price = min(formula_price, cap_price)
            price = max(price, prev_price)  # monotonic: L never cheaper than S/M
            price = round(price, 2)
            prev_price = price

            packages[(pname, tname)] = {
                "persona": pname,
                "tier": tname,
                "total_gb": pack_total_gb,
                "buckets_gb": buckets,
                "general_pool_gb": general_pool,
                "price_azn": price,
                "formula_price_azn": round(formula_price, 2),
                "existing_offer_price_azn": existing_price,
                "existing_offer_source": existing_src,
                "n_users_in_tier": len(tgroup),
                "coverage_within_tier": round(coverage, 4),
                "tier_gb_bounds": (round(float(q1 if tname == "S" else (q2 if tname == "L" else q1)), 2),
                                   round(float(q2 if tname != "L" else group["total_gb"].max()), 2)),
            }

    return packages


def assign_tier(total_gb: float, persona: str, packages: dict) -> str:
    candidates = [(t, packages[(persona, t)]) for t in ["S", "M", "L"] if (persona, t) in packages]
    if not candidates:
        return None
    fitting = [t for t, pkg in candidates if pkg["total_gb"] >= total_gb]
    if fitting:
        return min(fitting, key=lambda t: packages[(persona, t)]["total_gb"])
    return max(candidates, key=lambda x: x[1]["total_gb"])[0]


# ---------------------------------------------------------------------------
# 5. recommend(user)
# ---------------------------------------------------------------------------
def recommend(user_row: pd.Series, clf_bundle: dict, packages: dict, scaler=None):
    single = pd.DataFrame([user_row])
    feats = engineer_features(single)
    X = clf_bundle["scaler"].transform(feats[clf_bundle["feature_columns"]].values)
    persona = clf_bundle["best_model"].predict(X)[0]
    total_gb = feats["total_gb"].iloc[0]
    tier = assign_tier(total_gb, persona, packages)
    if tier is None:
        return {"persona": persona, "tier": None, "package": None, "reason": "no_package_for_persona"}
    pkg = packages[(persona, tier)]
    return {"persona": persona, "tier": tier, "total_gb_used": round(float(total_gb), 2), "package": pkg}


# ---------------------------------------------------------------------------
# 6. Economics evaluation
# ---------------------------------------------------------------------------
def economics_eval(df: pd.DataFrame, persona: pd.Series, packages: dict):
    total = df[SECTIONS].sum(axis=1)
    rows = []
    for i, uid in enumerate(df["user_id"]):
        p = persona.iloc[i]
        g = total.iloc[i]
        tier = assign_tier(g, p, packages)
        if tier is None:
            continue
        our_price = packages[(p, tier)]["price_azn"]
        existing_price, existing_src = cheapest_existing_offer(g)
        savings = existing_price - our_price
        rows.append(
            dict(user_id=uid, persona=p, tier=tier, total_gb=g, our_price=our_price,
                 existing_price=existing_price, existing_src=existing_src, user_savings=savings)
        )
    edf = pd.DataFrame(rows)
    return edf


def economics_summary(edf: pd.DataFrame) -> dict:
    return {
        "n_users": len(edf),
        "avg_user_savings_azn": round(edf["user_savings"].mean(), 3),
        "avg_operator_margin_change_azn": round(-edf["user_savings"].mean(), 3),
        "pct_users_who_save": round((edf["user_savings"] > 0).mean() * 100, 2),
        "pct_win_win": round(((edf["user_savings"] > 0) & (edf["user_savings"] < 0)).mean() * 100, 2),  # structurally 0, kept explicit
    }


